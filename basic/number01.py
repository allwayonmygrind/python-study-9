
#숫자 정수형(int) 실수형(float) 연산자

#사직연산

print(1+1)
print(5-1)
print(3*4)
print(7/2)
print(4/2)

#몫 나머지
print(7 // 2) #나눗셈 몫만 남기기
print(7 % 2) #나머지

print(divmod(7,2)) # (3,1) (몫,나머지)를 함께 출력함

#거듭제곱
print(2**5) # 2의 5제곱 2^5 32 

#자료형 확인 : type()
print(type(10)) # <class 'int'> 정수형
print(type(3.5)) # <class 'float'> 실수형
print(type(4/2)) # <class 'float'> 실수형
print(type(4//2)) # <class 'int'> 정수형

# 정수 <-> 실수 변환
print(int(3.5)) # 정수형으로 변환 / 데이터 손실이 있음 : 소수점 아래 버림
print(float(5)) # 실수형으로 변환 5.0
#print('100'+1) 파이썬에선 문자열 + 숫자 계산 안됨
print(int('100')+ 1) #가능
print('100'+str(1)) #숫자를 문자열로 바꿔서 문자열+문자열 1001 

# 실수 계산
print(0.1 + 0.2) # 0.30000000000000004
print((0.1+0.2)== 0.3) # false
print(round(0.1+0.2, 2)) #round는 반올림 함수

# 계산 우선순위

print(3+5*2) # 3+10 = 13
print((3+5)*2) # 8*2 = 16

# 숫자 표기, 큰 수 계산
print(1234567*9876543) # 다른 언어는 큰 수가 1byte보다 커서 큰 자리수는 오류가 나는데 파이썬은 됨
print(1000000)
print(1,000,000) # 1 0 0 라고 나옴 각자 1, 000, 000 으로 구분되어 1 0 0
print(1_000_000) # 숫자 가독성 측면으로 사용하는 구분자